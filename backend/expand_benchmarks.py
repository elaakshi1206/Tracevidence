def append_to_file(filepath, new_cases_str):
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    last_bracket = content.rfind('];')
    if last_bracket == -1:
        raise ValueError(f"Could not find closing bracket in {filepath}")
    
    updated = content[:last_bracket].rstrip() + '\n' + new_cases_str.strip() + '\n];\n'
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(updated)
    print(f"Successfully updated {filepath}")

